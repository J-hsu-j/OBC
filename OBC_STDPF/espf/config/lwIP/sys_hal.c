/* Includes ------------------------------------------------------------------*/
#include "sys.h"

/**
 * @brief  Returns the current time in milliseconds
 *         when LWIP_TIMERS == 1 and NO_SYS == 1
 * @param  None
 * @retval Current Time value
 */
u32_t sys_now(void)
{
    return HAL_GetTick();
}
